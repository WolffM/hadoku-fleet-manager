#!/usr/bin/env node
/**
 * check-consumer-imports — refuse to publish a build that drops something a
 * consumer imports (fleet-manager#67).
 *
 * WHY. 0.34.324 removed `BackstopReason` and `ClawState`. hadoku_site's
 * mgmt-api still imported both, and its Typecheck went red 17 times over ~1.9h
 * until the site caught up (3641a19). Nothing here knew the site used them:
 * this package's own `check` proves the package is consistent with ITSELF.
 *
 * WHAT. Every `import`/`export … from`/`import()` of `@wolffm/fleet-manager`
 * (and its subpaths) in each consumer (lib/consumer-imports.mjs) is written into
 * one probe file. `tsc` then type-checks that probe with `@wolffm/fleet-manager`
 * resolved to THIS checkout, through its own package.json `exports`, so the
 * candidate `dist/` and `scripts/` are what is judged. A removed export is
 * TS2305 (TS2724 when a near name survives), a removed subpath TS2307. Types
 * and values are both checked, since a `.d.ts` carries both.
 *
 * WHERE THE IMPORT LIST COMES FROM. Two sources, one extractor:
 *   --surface-url URL  mgmt-api's `GET /api/repo/consumer-imports`, with
 *                      FLEET_SERVICE_KEY. What the publish job uses: it reads
 *                      NO consumer source and needs no access to a private repo,
 *                      only the list of this package's own export names that the
 *                      consumer uses (operator, 2026-11-06).
 *   (default)          each consumer's shipped tree, through
 *                      lib/fleet-source.mjs with the caller's own gh auth: a
 *                      session's local run.
 *
 * Run AFTER `pnpm run build`; a missing `dist/` is a failure, not a pass.
 *
 * Unreadable is a failure: a consumer whose tree could not be read, or one in
 * which no import was found at all, fails ("I could not look" never renders as
 * "nothing is wrong"). A consumer that imports nothing from the package must
 * stop being named rather than be tolerated.
 *
 *   pnpm run check:consumers [--json] [--repo owner/name ...]
 *   FLEET_SERVICE_KEY=... node scripts/check-consumer-imports.mjs --surface-url <mgmt>/api/repo/consumer-imports
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, rmSync, symlinkSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { writeFileAtomic } from '../dist/lib/atomic-json.js';
import { PKG, SKIP, SOURCE, collectUses } from './lib/consumer-imports.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/**
 * The probe: one statement per distinct (spec, name, kind), each tagged with
 * its line so a tsc error maps back to the consumer files that use it.
 *
 * @param {Map<string, { spec: string, name: string | null, kind: string, usedBy: string[] }>} uses
 * @returns {{ text: string, byLine: Map<number, { spec: string, name: string | null, kind: string, usedBy: string[] }> }}
 */
export function buildProbe(uses) {
	const lines = [
		'// Generated by scripts/check-consumer-imports.mjs. One line per consumer binding.',
	];
	const byLine = new Map();
	let n = 0;
	for (const u of uses.values()) {
		n++;
		const local = `__u${n}`;
		let stmt;
		if (u.kind === 'type')
			stmt = `import type { ${u.name} as ${local} } from '${u.spec}'; export type { ${local} };`;
		else if (u.kind === 'value')
			stmt = `import { ${u.name} as ${local} } from '${u.spec}'; export { ${local} };`;
		else if (u.kind === 'default') stmt = `import ${local} from '${u.spec}'; export { ${local} };`;
		else stmt = `import * as ${local} from '${u.spec}'; export { ${local} };`;
		lines.push(stmt);
		byLine.set(lines.length, u);
	}
	return { text: lines.join('\n') + '\n', byLine };
}

/**
 * The probe's compiler options. The JS subpath exports (fleet-source,
 * tier-detectors, ...) carry no .d.ts, so tsc reads their exports from the
 * .mjs itself (`allowJs` + `maxNodeModuleJsDepth`).
 */
const TSC_FLAGS = [
	'--module',
	'nodenext',
	'--moduleResolution',
	'nodenext',
	'--target',
	'es2022',
	'--strict',
	'--noEmit',
	'--skipLibCheck',
	'--allowJs',
	'--maxNodeModuleJsDepth',
	'1',
	'--pretty',
	'false',
];

/**
 * Type-check the probe against the package at `pkgRoot`. Returns tsc's
 * diagnostics for probe lines, each mapped to the binding on that line.
 */
export function typecheckProbe(probe, { pkgRoot = ROOT, tsc } = {}) {
	const dir = mkdtempSync(join(tmpdir(), 'consumer-imports-'));
	try {
		const scope = join(dir, 'node_modules', '@wolffm');
		mkdirSync(scope, { recursive: true });
		symlinkSync(pkgRoot, join(scope, 'fleet-manager'), 'dir');
		// `.mts`: ESM by its extension, so no package.json is written to say so,
		// and the options go on the command line rather than into a tsconfig.
		writeFileAtomic(join(dir, 'probe.mts'), probe.text);
		const bin = tsc ?? createRequire(join(ROOT, 'package.json')).resolve('typescript/bin/tsc');
		let output = '';
		try {
			execFileSync(process.execPath, [bin, ...TSC_FLAGS, 'probe.mts'], {
				cwd: dir,
				encoding: 'utf8',
				stdio: ['ignore', 'pipe', 'pipe'],
			});
		} catch (err) {
			output = `${err.stdout ?? ''}${err.stderr ?? ''}`;
			if (!output.trim()) throw new Error(`tsc failed with no output: ${err.message}`);
		}
		const findings = [];
		const other = [];
		for (const line of output.split('\n').filter(Boolean)) {
			const m = /^probe\.mts\((\d+),\d+\): error (TS\d+): (.*)$/.exec(line);
			const use = m && probe.byLine.get(Number(m[1]));
			if (use) findings.push({ ...use, code: m[2], error: m[3] });
			else other.push(line);
		}
		return { findings, other };
	} finally {
		rmSync(dir, { recursive: true, force: true });
	}
}

/**
 * The import lists mgmt-api serves (`GET /api/repo/consumer-imports`), built
 * there from the deployed consumer trees with lib/consumer-imports.mjs, so the
 * publish job reads NO consumer source and holds no read access to any private
 * repo. The caller's repo is derived from its service key.
 *
 * Response: `{ success: true, package, consumers: [{ repo, sha, bindings:
 * [{ spec, name, kind, usedBy }] }] }`. Anything else is "could not look".
 */
export async function surfaceFromUrl(url, key, fetchImpl = fetch) {
	let res;
	try {
		res = await fetchImpl(url, {
			headers: { 'X-User-Key': key, 'User-Agent': 'fleet-manager-consumer-imports' },
			signal: AbortSignal.timeout(60_000),
		});
	} catch (err) {
		throw new Error(`GET ${url}: ${err.message}`);
	}
	const text = await res.text();
	let body;
	try {
		body = JSON.parse(text);
	} catch {
		throw new Error(`GET ${url}: HTTP ${res.status}, not JSON: ${text.slice(0, 200)}`);
	}
	if (!res.ok || body?.success !== true || !Array.isArray(body.consumers))
		throw new Error(
			`GET ${url}: HTTP ${res.status} ${body?.error ?? body?.message ?? JSON.stringify(body).slice(0, 200)}`
		);
	return body.consumers.map((c) => ({
		repo: c.repo,
		sha: c.sha,
		uses: new Map(
			(c.bindings ?? []).map((u) => [
				`${u.spec}\0${u.name}\0${u.kind}`,
				{ ...u, usedBy: u.usedBy ?? [] },
			])
		),
	}));
}

/** Each consumer's bindings, read from its shipped tree through lib/fleet-source.mjs. */
async function surfaceFromSource(repos, unreadable) {
	const { shipped, UnreadableRepo } = await import('./lib/fleet-source.mjs');
	const out = [];
	for (const repo of repos) {
		try {
			const handle = shipped(repo);
			const paths = handle.list().filter((p) => SOURCE.test(p) && !SKIP.test(p));
			out.push({
				repo,
				sha: handle.sha,
				uses: collectUses(handle.readMany(paths)),
				files: paths.length,
			});
		} catch (err) {
			if (!(err instanceof UnreadableRepo)) throw err;
			unreadable.push(`${repo}: ${err.message}`);
		}
	}
	return out;
}

async function main(argv) {
	const json = argv.includes('--json');
	const valued = (flag) => argv.flatMap((a, i) => (argv[i - 1] === flag ? [a] : []));
	const repos = valued('--repo');
	const surfaceUrl = valued('--surface-url')[0];
	const result = { ok: true, consumers: [], findings: [], unreadable: [] };

	if (!existsSync(join(ROOT, 'dist', 'index.d.ts'))) {
		result.ok = false;
		result.unreadable.push(
			'dist/index.d.ts is missing: run `pnpm run build` first; nothing was checked'
		);
	} else {
		let surfaces = [];
		if (surfaceUrl) {
			const key = process.env.FLEET_SERVICE_KEY;
			if (!key)
				result.unreadable.push('--surface-url needs FLEET_SERVICE_KEY: nothing was checked');
			else {
				try {
					surfaces = await surfaceFromUrl(surfaceUrl, key);
					if (!surfaces.length) result.unreadable.push(`${surfaceUrl} named no consumer at all`);
				} catch (err) {
					result.unreadable.push(err.message);
				}
			}
		} else if (!repos.length)
			result.unreadable.push('name the consumers to read: --repo owner/name (or --surface-url)');
		else surfaces = await surfaceFromSource(repos, result.unreadable);

		for (const { repo, sha, uses, files } of surfaces) {
			if (!uses.size) {
				result.unreadable.push(
					`${repo}@${String(sha).slice(0, 7)}: no import of ${PKG} found${files === undefined ? '' : ` in ${files} files`}; ` +
						'either the reader is broken or it is no longer a consumer'
				);
				continue;
			}
			const { findings, other } = typecheckProbe(buildProbe(uses));
			result.consumers.push({ repo, sha, bindings: uses.size, broken: findings.length });
			for (const f of findings) result.findings.push({ repo, ...f });
			if (other.length)
				result.unreadable.push(`${repo}: tsc reported outside the probe: ${other.join(' | ')}`);
		}
	}
	result.ok = result.ok && !result.findings.length && !result.unreadable.length;

	if (json) process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
	else {
		for (const c of result.consumers)
			console.log(
				`${c.repo}@${c.sha.slice(0, 7)}: ${c.bindings} binding(s) from ${PKG}, ${c.broken} broken`
			);
		for (const f of result.findings)
			console.log(
				`BROKEN ${f.repo}: ${f.kind} ${f.name ?? '(module)'} from '${f.spec}' — ${f.code} ${f.error}\n  used by ${f.usedBy.join(', ')}`
			);
		for (const u of result.unreadable) console.log(`COULD NOT LOOK ${u}`);
		console.log(
			result.ok
				? 'ok: every consumer import resolves against this build'
				: 'REFUSED: this build breaks a consumer, or a consumer could not be read'
		);
	}
	return result.ok ? 0 : 1;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
	process.exitCode = await main(process.argv.slice(2));
}
