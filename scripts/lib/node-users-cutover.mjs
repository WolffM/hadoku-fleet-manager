/**
 * THE CUTOVER: one node's CI moves off the admin user onto its own
 * (docs/planning/node-users-2026-10-27.md §8, P3).
 *
 * Three node scripts and one manifest edit, all pure text here so the tests
 * can read them; `scripts/node-users.mjs --cutover` runs them.
 *
 *   inventoryScript   READ ONLY. What would move, how big, what would be
 *                     re-pointed, and whether the node is quiet enough.
 *   cutoverScript     the change, as admin with sudo. IDEMPOTENT: every step
 *                     checks before it acts, so a run killed halfway is
 *                     finished by running it again.
 *   backScript        the rollback: every path the cutover RECORDED moving
 *                     goes back, links and text are re-pointed home, and the
 *                     ci user loses its key and linger. The user is kept,
 *                     locked, so a second attempt reuses its uid.
 *
 * MOVED, NOT COPIED. These trees are ~30 GB on claw-5, and a copy would double
 * that on small disks. Both homes are on one filesystem, so `mv` is a rename
 * and costs nothing; `chown -R` is the slow part.
 *
 * Every script prints `STEP <name> <ok|skip|fail> <detail>` lines and ends
 * with `CUTOVER-END` / `INVENTORY-END` / `BACK-END`. A missing end marker is a
 * run that did not finish, never a pass.
 */
import { JIT_PAYLOAD_DIR } from './preflight.mjs';

/**
 * What moves from admin's home to ci's, measured on claw-5 (§8). The first is
 * the runner tree: slots, the payload, the throttle hook and its env files.
 * Everything else is a toolchain or a cache a job writes.
 */
export const MOVES = [
	JIT_PAYLOAD_DIR.split('/')[0],
	// Standing runners (the bootstrap guarantee keeps one per node it is
	// resident on); their units travel with them, see STANDING.
	'runners',
	'.cargo',
	'.rustup',
	'.gradle',
	'.android',
	'.m2',
	'.npm',
	'setup-pnpm',
	'runner-tmp',
	'.cache',
	'.local',
	'.docker',
	'.pki',
	'.npmrc',
];

/** `.config` moves child by child, except what admin's own systemd manager reads. */
export const CONFIG_STAYS = ['systemd'];

/**
 * Text files that carry the old home as an absolute path, and are not
 * regenerated by a redeploy: uv's tool shebangs and every venv's
 * `pyvenv.cfg`. Bounded on purpose: a grep over the pnpm store and the
 * caches takes minutes and finds nothing a job reads. Anything missed fails
 * bootcamp's re-prove as ci, before the node takes a job.
 */
export const REWRITE_TREES = ['.local/share/uv', '.local/bin', '.cargo/env'];

/** System places a toolchain repair linked INTO admin's home (`/usr/local/bin/rustc` and friends). */
export const LINK_DIRS = ['/usr/local/bin', '/opt/hostedtoolcache'];

/** The record of what this cutover moved; `--back` reads it. Root-owned, outside both homes. */
export const RECORD = '/var/lib/fleet-node-users/moved';

/**
 * The standing runner units the cutover took from admin's manager and gives to
 * ci's: `--back` reads it to hand them back. A standing runner is the bootstrap
 * guarantee (this repo's own runner, which ships the fix when minting is
 * broken), so it is moved, never stopped and left (claw-4, 2026-10-28).
 */
export const STANDING = '/var/lib/fleet-node-users/standing';

const NAME = /^[a-z_][a-z0-9_-]*$/;
const KEY = /^(ssh-ed25519|ssh-rsa|ecdsa-sha2-nistp(256|384|521)) [A-Za-z0-9+/=]+$/;

function header({ admin, ci, adminHome, ciHome }) {
	for (const [k, v] of Object.entries({ admin, ci }))
		if (!NAME.test(v ?? '')) throw new Error(`refusing ${k} user ${JSON.stringify(v)}`);
	if (admin === ci) throw new Error(`the ci user must not be admin (${admin})`);
	for (const [k, v] of Object.entries({ adminHome, ciHome }))
		if (!/^\/home\/[a-z_][a-z0-9_-]*$/.test(v ?? '')) throw new Error(`refusing ${k} ${v}`);
	return `set -u
ADMIN='${admin}'
CI='${ci}'
AH='${adminHome}'
CH='${ciHome}'
RECORD='${RECORD}'
STANDING='${STANDING}'
as_ci() { sudo -n -u "$CI" XDG_RUNTIME_DIR="/run/user/$(id -u "$CI")" "$@"; }
step() { printf 'STEP %s %s %s\\n' "$1" "$2" "\${3:-}"; }
die() { step "$1" fail "$2"; exit 1; }
# ci's home is 0700, so ADMIN cannot stat inside it: every existence test on a
# path under $CH goes through sudo. A plain [ -e ] there reads "absent" for
# everything (claw-5, 2026-10-27: 13 system links and 37 uv files skipped).
ci_has() { sudo -n test -e "$1" || sudo -n test -L "$1"; }
# The users sshd lets in, from its EFFECTIVE config; empty means no allow-list.
allowed() { sudo -n sshd -T 2>/dev/null | awk 'tolower($1)=="allowusers"{for(i=2;i<=NF;i++) print $i}'; }
allow_conf() { sudo -n grep -lsE '^[[:space:]]*[Aa]llow[Uu]sers[[:space:]]' /etc/ssh/sshd_config.d/*.conf /etc/ssh/sshd_config | head -1; }
busy=$(pgrep -xc 'Runner\\.Worker' 2>/dev/null || true)
`;
}

const moveList = () => MOVES.map((m) => `'${m}'`).join(' ');
const linkDirs = () => LINK_DIRS.map((d) => `'${d}'`).join(' ');

/** READ ONLY: what a cutover would do here. */
export function inventoryScript(users) {
	return `${header(users)}
echo INVENTORY-BEGIN
step quiet "$([ "\${busy:-0}" = 0 ] && echo ok || echo fail)" "\${busy:-unknown} job(s) running"
if getent passwd "$CI" >/dev/null; then step user ok "$CI exists (uid $(id -u "$CI"))"; else step user skip "$CI would be created"; fi
for p in ${moveList()}; do
	if [ -e "$AH/$p" ]; then
		if ci_has "$CH/$p"; then
			if grep -qxF "$p" "$RECORD" 2>/dev/null; then step "move:$p" skip "moved; $ADMIN has its own since, left there"
			else step "move:$p" fail "both homes hold it"; fi
			continue
		fi
		sz=$(timeout 20 du -sh "$AH/$p" 2>/dev/null | cut -f1)
		step "move:$p" ok "\${sz:-size not read in 20s}"
	elif ci_has "$CH/$p"; then step "move:$p" skip "already moved"
	else step "move:$p" skip "absent"; fi
done
for c in "$AH"/.config/* "$AH"/.config/.[!.]*; do
	[ -e "$c" ] || continue
	n=\${c##*/}
	case " ${CONFIG_STAYS.join(' ')} " in *" $n "*) step "config:$n" skip "stays with admin"; continue ;; esac
	step "config:$n" ok "moves"
done
links=$(find ${linkDirs()} -maxdepth 6 -type l -lname "$AH/*" 2>/dev/null | wc -l)
step links ok "$links system link(s) into $AH to re-point"
if [ -z "$(allowed)" ]; then step sshd ok "no AllowUsers list"
elif allowed | grep -qx "$CI"; then step sshd skip "AllowUsers already names $CI"
else step sshd ok "AllowUsers names $(allowed | tr '\\n' ' '); $CI is added"; fi
step free ok "$(df -h "$AH" | awk 'NR==2{print $4}') free"
echo INVENTORY-END
`;
}

/**
 * The cutover itself, as ADMIN. `controllerKeys` are the controller's public
 * keys (`type base64` each): the ci user's authorized_keys gets every line of
 * ADMIN's whose key is one of them, re-written with `from=` the address this
 * session came from and `restrict`, so the key works for nothing but commands
 * from the controller.
 */
export function cutoverScript(users, { controllerKeys }) {
	const keys = (controllerKeys ?? []).filter((k) => KEY.test(k));
	if (!keys.length) throw new Error('no controller public key to install for the ci user');
	return `${header(users)}
set -o pipefail
KEYS='${keys.join('\n')}'
echo CUTOVER-BEGIN
[ "$HOME" = "$AH" ] || die preflight "running as $HOME, not admin's $AH"
sudo -n true 2>/dev/null || die preflight "admin has no non-interactive sudo"
[ "\${busy:-1}" = 0 ] || die preflight "\${busy:-unknown} job(s) running: drain the node and wait"
step preflight ok "quiet"

# 1. The user. useradd allocates /etc/subuid and /etc/subgid ranges itself
#    (rootless docker needs them); a user made before that is given one.
if ! getent passwd "$CI" >/dev/null; then
	sudo -n useradd --create-home --home-dir "$CH" --shell /bin/bash --user-group "$CI" || die user "useradd failed"
fi
sudo -n usermod --unlock "$CI" >/dev/null 2>&1 || true
sudo -n chown "$CI:$CI" "$CH" && sudo -n chmod 0700 "$CH" || die user "could not own $CH"
if ! grep -q "^$CI:" /etc/subuid || ! grep -q "^$CI:" /etc/subgid; then
	next=$(cat /etc/subuid /etc/subgid 2>/dev/null | awk -F: 'BEGIN{m=100000} {e=$2+$3; if (e>m) m=e} END{print m}')
	sudo -n usermod --add-subuids "$next-$((next + 65535))" --add-subgids "$next-$((next + 65535))" "$CI" || die user "no subordinate ids"
fi
sudo -n loginctl enable-linger "$CI" || die user "could not enable linger"
step user ok "$CI uid $(id -u "$CI"), 0700, linger"

# 2. The key: admin's lines for the controller's keys, restricted to this address.
from=\${SSH_CLIENT%% *}
[ -n "$from" ] || die key "no SSH_CLIENT: run this over the controller's ssh"
ak=$(while read -r t b; do
	grep -qF " $b" "$AH/.ssh/authorized_keys" && printf 'from="%s",restrict %s %s fleet-controller\\n' "$from" "$t" "$b"
done <<<"$KEYS")
[ -n "$ak" ] || die key "none of the controller's keys is in $AH/.ssh/authorized_keys"
sudo -n install -d -m 0700 -o "$CI" -g "$CI" "$CH/.ssh"
printf '%s\\n' "$ak" | sudo -n tee "$CH/.ssh/authorized_keys" >/dev/null
sudo -n chown "$CI:$CI" "$CH/.ssh/authorized_keys" && sudo -n chmod 0600 "$CH/.ssh/authorized_keys"
step key ok "$(printf '%s\\n' "$ak" | wc -l) key(s), from=$from, restrict"

# 2b. sshd must LET ci in. node-bootstrap's AllowUsers names admin alone, and
#     sshd refuses an unlisted user before it reads a key: claw-5, 2026-10-28,
#     every controller ssh as ci was "Permission denied (publickey)".
if [ -n "$(allowed)" ] && ! allowed | grep -qx "$CI"; then
	conf=$(allow_conf)
	[ -n "$conf" ] || die sshd "sshd has an AllowUsers list but no file under /etc/ssh names it"
	sudo -n cp -p "$conf" "$conf.fleet-bak" || die sshd "could not back up $conf"
	sudo -n sed -i -E "s/^([[:space:]]*[Aa]llow[Uu]sers[[:space:]].*)$/\\1 $CI/" "$conf"
	if ! sudo -n sshd -t; then
		sudo -n mv "$conf.fleet-bak" "$conf"
		die sshd "sshd rejected $conf with $CI added; restored"
	fi
	sudo -n rm -f "$conf.fleet-bak"
	sudo -n systemctl reload ssh || die sshd "ssh did not reload"
fi
[ -z "$(allowed)" ] || allowed | grep -qx "$CI" || die sshd "sshd's effective AllowUsers still leaves out $CI"
step sshd ok "$CI may log in"

# 3. Admin stops running CI: its harvester and any minted unit.
systemctl --user disable --now runner-mem-harvest.service >/dev/null 2>&1 || true
systemctl --user stop 'jit-*' 'warm-*' >/dev/null 2>&1 || true
# A standing runner is MOVED, not left behind: recorded, stopped here, its unit
# moved with its tree below, and started again in ci's manager at the end.
sudo -n install -d -m 0755 "\${STANDING%/*}"
for u in $(systemctl --user list-unit-files --no-legend 'actions-runner-*.service' 2>/dev/null | awk '{print $1}'); do
	grep -qxF "$u" "$STANDING" 2>/dev/null || echo "$u" | sudo -n tee -a "$STANDING" >/dev/null
	systemctl --user disable --now "$u" >/dev/null 2>&1 || die stop "could not stop standing runner $u"
done
left=$(pgrep -xc -u "$ADMIN" 'Runner\\.(Listener|Worker)' 2>/dev/null || true)
[ "\${left:-0}" = 0 ] || die stop "$left runner process(es) still run as $ADMIN outside any unit this script knows"
step stop ok "no runner runs as $ADMIN$([ -s "$STANDING" ] && printf '; standing, to move: %s' "$(tr '\\n' ' ' < "$STANDING")")"

# 3b. /tmp. A job that wrote a FIXED name there (report-job's
#     /tmp/report-job.json) left a file ci can never overwrite: /tmp is sticky.
#     On claw-5 that turned every green job red with "Permission denied". With
#     admin's CI stopped, an admin-owned top-level file nothing holds open is
#     that debris. Named, so the run says what it removed.
swept=""
while IFS= read -r f; do
	sudo -n fuser -s "$f" 2>/dev/null && continue
	rm -f "$f" && swept="$swept \${f##*/}"
done < <(find /tmp -maxdepth 1 -type f -user "$ADMIN" 2>/dev/null)
step tmp ok "\${swept:+removed CI leftovers of $ADMIN from /tmp:$swept}\${swept:-no admin-owned file left in /tmp}"

# 4. Move. Each path is recorded BEFORE it moves, so --back knows it even if
#    this run dies mid-mv.
sudo -n install -d -m 0755 "\${RECORD%/*}"
record() { grep -qxF "$1" "$RECORD" 2>/dev/null || echo "$1" | sudo -n tee -a "$RECORD" >/dev/null; }
moved=0
reappeared=""
# A path the record already holds and ci's home has was moved by an earlier
# run. If admin's home has it AGAIN, something wrote it after the move (the
# provisioning converger, before the deployed manifest had the flip): it is
# left in place and named, never moved over ci's copy.
mv1() {
	if [ -e "$AH/$1" ] || [ -L "$AH/$1" ]; then
		if ci_has "$CH/$1"; then
			grep -qxF "$1" "$RECORD" 2>/dev/null || die "move:$1" "both homes hold $1"
			reappeared="$reappeared $1"
			return 0
		fi
		record "$1"
		sudo -n mv "$AH/$1" "$CH/$1" || die "move:$1" "mv failed"
		moved=$((moved + 1))
	fi
}
for p in ${moveList()}; do mv1 "$p"; done
if [ -d "$AH/.config" ]; then
	sudo -n install -d -m 0700 -o "$CI" -g "$CI" "$CH/.config"
	for c in "$AH"/.config/* "$AH"/.config/.[!.]*; do
		[ -e "$c" ] || continue
		n=\${c##*/}
		case " ${CONFIG_STAYS.join(' ')} " in *" $n "*) continue ;; esac
		mv1 ".config/$n"
	done
fi
if [ -s "$STANDING" ]; then
	sudo -n install -d -m 0755 -o "$CI" -g "$CI" "$CH/.config/systemd" "$CH/.config/systemd/user"
	while IFS= read -r u; do
		mv1 ".config/systemd/user/$u"
		mv1 ".config/systemd/user/$u.d"
	done < "$STANDING"
fi
step move ok "$moved path(s) moved this run\${reappeared:+; reappeared in $AH after the move, left there:$reappeared}"

# 5. Own it. The whole new home, and the toolcache jobs write into.
sudo -n chown -R "$CI:$CI" "$CH" || die chown "chown of $CH failed"
for d in ${linkDirs()}; do
	[ "$d" = /usr/local/bin ] && continue
	[ -d "$d" ] && { sudo -n chown -R "$CI:$CI" "$d" || die chown "chown of $d failed"; }
done
step chown ok "$CH and the toolcache are $CI's"

# 6. Links that pointed into admin's home, system-wide and inside the moved trees.
relinked=0
while IFS= read -r l; do
	t=$(readlink "$l")
	rest=\${t#"$AH"/}
	top=\${rest%%/*}
	[ "$top" = .config ] && top=.config/$(printf '%s' "$rest" | cut -d/ -f2)
	ci_has "$CH/$top" || continue
	sudo -n ln -sfn "$CH/$rest" "$l" && relinked=$((relinked + 1))
	case "$l" in "$CH"/*) sudo -n chown -h "$CI:$CI" "$l" ;; esac
done < <(sudo -n find ${linkDirs()} "$CH" -type l -lname "$AH/*" 2>/dev/null)
step relink ok "$relinked link(s) re-pointed"

# 7. Text that names the old home. As ci, so every file stays ci's.
rewritten=0
for t in ${REWRITE_TREES.map((t) => `'${t}'`).join(' ')}; do
	ci_has "$CH/$t" || continue
	while IFS= read -r f; do
		sudo -n -u "$CI" sed -i -E "s#$AH(/|\\$|[^-a-zA-Z0-9_])#$CH\\1#g" "$f" && rewritten=$((rewritten + 1))
	done < <(sudo -n grep -rlI -- "$AH/" "$CH/$t" 2>/dev/null)
done
# A standing runner's .env (hook paths, TMPDIR) and .path; never its _work.
while IFS= read -r f; do
	sudo -n grep -qF -- "$AH/" "$f" || continue
	sudo -n -u "$CI" sed -i -E "s#$AH(/|\\$|[^-a-zA-Z0-9_])#$CH\\1#g" "$f" && rewritten=$((rewritten + 1))
done < <(sudo -n find "$CH/runners" -mindepth 2 -maxdepth 2 -type f \\( -name .env -o -name .path \\) 2>/dev/null)
step rewrite ok "$rewritten file(s) re-pointed"

# 8. Nothing of the moved trees may still name the old home through a link.
stale=$(sudo -n find ${linkDirs()} -maxdepth 6 -type l -lname "$AH/*" 2>/dev/null | wc -l)
[ "$stale" = 0 ] || die verify "$stale system link(s) still point into $AH"
step verify ok "no system link points into $AH"

# 9. The standing runners, back up in ci's manager.
if [ -s "$STANDING" ]; then
	as_ci systemctl --user daemon-reload || die standing "ci's manager did not reload"
	while IFS= read -r u; do
		as_ci systemctl --user enable --now "$u" >/dev/null 2>&1 || die standing "$u did not start as $CI"
		as_ci systemctl --user is-active -q "$u" || die standing "$u is not active as $CI"
	done < "$STANDING"
	step standing ok "$(wc -l < "$STANDING") standing runner(s) run as $CI: $(tr '\\n' ' ' < "$STANDING")"
fi
echo CUTOVER-END
`;
}

/** The rollback, as ADMIN: the cutover in reverse, from its record. */
export function backScript(users) {
	return `${header(users)}
set -o pipefail
echo BACK-BEGIN
[ "$HOME" = "$AH" ] || die preflight "running as $HOME, not admin's $AH"
[ "\${busy:-1}" = 0 ] || die preflight "\${busy:-unknown} job(s) running: drain the node and wait"
uid=$(id -u "$CI" 2>/dev/null) || die preflight "$CI does not exist: nothing to roll back"
step preflight ok "quiet"

# ci stops running CI: every unit in its manager, then its linger and key.
sudo -n systemctl --user -M "$CI@" stop 'jit-*' 'warm-*' runner-mem-harvest.service docker.service >/dev/null 2>&1 || true
if [ -s "$STANDING" ]; then
	while IFS= read -r u; do as_ci systemctl --user disable --now "$u" >/dev/null 2>&1 || true; done < "$STANDING"
fi
left=$(pgrep -xc -u "$CI" 'Runner\\.(Listener|Worker)' 2>/dev/null || true)
[ "\${left:-0}" = 0 ] || die stop "$left runner process(es) still run as $CI"
sudo -n loginctl disable-linger "$CI" || true
sudo -n rm -f "$CH/.ssh/authorized_keys"
conf=$(allow_conf)
if [ -n "$conf" ] && allowed | grep -qx "$CI"; then
	sudo -n sed -i -E "/^[[:space:]]*[Aa]llow[Uu]sers[[:space:]]/ s/[[:space:]]$CI([[:space:]]|$)/\\1/" "$conf"
	sudo -n sshd -t && sudo -n systemctl reload ssh || die stop "sshd did not take $CI out of AllowUsers"
fi
sudo -n usermod --lock "$CI" >/dev/null 2>&1 || true
step stop ok "$CI has no key, no linger, and runs nothing"

[ -s "$RECORD" ] || die move "no record at $RECORD: nothing to move back"
n=0
while IFS= read -r p; do
	[ -n "$p" ] || continue
	if ci_has "$CH/$p"; then
		[ -e "$AH/$p" ] && die "move:$p" "both homes hold $p"
		sudo -n install -d -o "$ADMIN" -g "$ADMIN" "$AH/$(dirname "$p")"
		sudo -n mv "$CH/$p" "$AH/$p" || die "move:$p" "mv failed"
		sudo -n chown -R "$ADMIN:$ADMIN" "$AH/$p"
		n=$((n + 1))
	fi
done < "$RECORD"
for d in ${linkDirs()}; do
	[ "$d" = /usr/local/bin ] && continue
	[ -d "$d" ] && sudo -n chown -R "$ADMIN:$ADMIN" "$d"
done
step move ok "$n path(s) moved back"

while IFS= read -r l; do
	t=$(readlink "$l")
	sudo -n ln -sfn "$AH/\${t#"$CH"/}" "$l"
	case "$l" in "$AH"/*) sudo -n chown -h "$ADMIN:$ADMIN" "$l" ;; esac
done < <(sudo -n find ${linkDirs()} "$AH" -type l -lname "$CH/*" 2>/dev/null)
for t in ${REWRITE_TREES.map((t) => `'${t}'`).join(' ')}; do
	[ -e "$AH/$t" ] || continue
	while IFS= read -r f; do
		sed -i "s#$CH#$AH#g" "$f"
	done < <(grep -rlI -- "$CH/" "$AH/$t" 2>/dev/null)
done
step relink ok "links and text point home again"

systemctl --user enable --now runner-mem-harvest.service >/dev/null 2>&1 || true
if [ -s "$STANDING" ]; then
	systemctl --user daemon-reload
	while IFS= read -r u; do
		systemctl --user enable --now "$u" >/dev/null 2>&1 || die standing "$u did not start as $ADMIN"
	done < "$STANDING"
	sudo -n mv "$STANDING" "$STANDING.back-$(date +%s)"
fi
sudo -n mv "$RECORD" "$RECORD.back-$(date +%s)"
echo BACK-END
`;
}

/** `{ steps: [{ name, status, detail }], complete }` from any of the three. */
export function parseSteps(stdout, end) {
	const text = String(stdout ?? '');
	const steps = [];
	for (const line of text.split('\n')) {
		const m = /^STEP (\S+) (ok|skip|fail) ?(.*)$/.exec(line);
		if (m) steps.push({ name: m[1], status: m[2], detail: m[3] });
	}
	return { steps, complete: text.includes(end) };
}

/**
 * The manifest edit: `users.ci` (and, where the operator gave this node a
 * rootless daemon, `containers: "docker"`). `back` removes both. Returns the
 * machine entry it changed, or throws on a node the manifest does not have.
 */
export function flipManifest(doc, node, { ci, docker = false, back = false }) {
	const m = doc.machines?.[node];
	if (!m) throw new Error(`${node} is not in the manifest`);
	if (back) {
		if (m.users) {
			delete m.users.ci;
			if (!Object.keys(m.users).length) delete m.users;
		}
		delete m.containers;
		return m;
	}
	if (!NAME.test(ci ?? '')) throw new Error(`refusing ci user ${JSON.stringify(ci)}`);
	m.users = { ...(m.users ?? {}), ci };
	if (docker) m.containers = 'docker';
	return m;
}
